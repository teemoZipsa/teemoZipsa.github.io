import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const origin = 'https://teemozipsa.com';
const liveMode = process.argv.includes('--live');

const placeholderPatterns = [
  /ARTICLE_/i,
  /본문 내용이 여기에/,
  /AdSense Slot/i,
  /Content generated by (AI|Teemo AI|AI Assistant)/i,
  /SEO를 위한 요약/,
  /썸네일이미지절대경로/,
  /responsive ·/,
  /HERO IMAGE/i,
  /drop original/i,
  /프로모션 영역/,
  /광고 영역/,
  /href=["']article\.html["']/i
];

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

function rel(file) {
  return path.relative(rootDir, file).replace(/\\/g, '/');
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['.git', 'node_modules'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.toLowerCase().endsWith('.html')) out.push(full);
  }
  return out;
}

function parseSitemap(file = path.join(rootDir, 'sitemap.xml')) {
  const xml = read(file);
  return [...xml.matchAll(/<loc>(https:\/\/teemozipsa\.com[^<]+)<\/loc>/g)].map(m => m[1]);
}

function fileForUrl(url) {
  const { pathname } = new URL(url);
  if (pathname === '/') return path.join(rootDir, 'index.html');
  if (pathname.endsWith('/')) return path.join(rootDir, pathname.slice(1), 'index.html');
  return path.join(rootDir, pathname.slice(1));
}

function urlForFile(file) {
  const r = rel(file);
  if (r === 'index.html') return `${origin}/`;
  if (r.endsWith('/index.html')) return `${origin}/${r.slice(0, -'index.html'.length)}`;
  return `${origin}/${r}`;
}

function getTag(html, name) {
  const re = new RegExp(`<meta\\s+[^>]*name=["']${name}["'][^>]*content=(["'])(.*?)\\1[^>]*>`, 'i');
  return html.match(re)?.[2]?.trim() || '';
}

function getProperty(html, property) {
  const re = new RegExp(`<meta\\s+[^>]*property=["']${property}["'][^>]*content=(["'])(.*?)\\1[^>]*>`, 'i');
  return html.match(re)?.[2]?.trim() || '';
}

function getTitle(html) {
  return html.match(/<title>([\s\S]*?)<\/title>/i)?.[1]?.replace(/\s+/g, ' ').trim() || '';
}

function getCanonical(html) {
  return html.match(/<link\s+[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["'][^>]*>/i)?.[1]?.trim() || '';
}

function getRefreshTarget(html) {
  const content = html.match(/<meta\s+[^>]*http-equiv=["']refresh["'][^>]*content=["'][^"']*url=\s*([^"';]+)["'][^>]*>/i)?.[1]?.trim();
  return content ? new URL(content, origin).href : '';
}

function hasNoindex(html) {
  return /<meta\s+[^>]*(?:name|property)=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html);
}

function stripHtml(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function internalLinks(html) {
  const htmlOnly = html.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ');
  return [...htmlOnly.matchAll(/\s(?:href|src)=["']([^"']+)["']/gi)]
    .map(m => m[1].trim())
    .filter(href => href && !href.startsWith('#'))
    .filter(href => !/^(https?:)?\/\//i.test(href))
    .filter(href => !/^(mailto:|tel:|javascript:|data:|blob:)/i.test(href));
}

function localTargetExists(href, fromFile) {
  const noQuery = href.split(/[?#]/)[0];
  if (!noQuery || noQuery.startsWith('#')) return true;
  const baseDir = path.dirname(fromFile);
  let target;
  if (noQuery.startsWith('/')) target = path.join(rootDir, noQuery.slice(1));
  else target = path.resolve(baseDir, noQuery);
  if (noQuery.endsWith('/')) target = path.join(target, 'index.html');
  return fs.existsSync(target);
}

function localAudit() {
  const failures = [];
  const warnings = [];
  const sitemapUrls = parseSitemap();
  const sitemapSet = new Set(sitemapUrls);
  const toolSitemapUrls = parseSitemap(path.join(rootDir, 'special-chars', 'sitemap.xml'));
  const toolSitemapSet = new Set(toolSitemapUrls);
  const expectedToolUrls = sitemapUrls.filter(url => new URL(url).pathname.startsWith('/special-chars/'));
  const publicHtmlFiles = walk(rootDir).filter(file => {
    const r = rel(file);
    if (r.startsWith('scripts/')) return false;
    if (r === 'special-chars/404.html') return false;
    return true;
  });

  for (const url of sitemapUrls) {
    const file = fileForUrl(url);
    if (!fs.existsSync(file)) failures.push(`sitemap URL has no local file: ${url}`);
  }

  for (const file of publicHtmlFiles) {
    const r = rel(file);
    const expectedUrl = urlForFile(file);
    const html = read(file);
    const noindex = hasNoindex(html);
    const hasAdSenseLoader = /pagead2\.googlesyndication\.com\/pagead\/js\/adsbygoogle\.js/i.test(html);
    if (noindex && sitemapSet.has(expectedUrl)) failures.push(`${r}: noindex page is present in sitemap (${expectedUrl})`);
    if (!noindex && !sitemapSet.has(expectedUrl)) failures.push(`${r}: indexable public HTML is missing from sitemap (${expectedUrl})`);
    if (hasAdSenseLoader && (r === 'index.html' || noindex || r.startsWith('special-chars/'))) {
      failures.push(`${r}: AdSense loader is present on a portal, noindex page, or utility page`);
    }

    for (const pattern of placeholderPatterns) {
      if (pattern.test(html)) failures.push(`${r}: contains placeholder/editorial-risk marker (${pattern})`);
    }
    const title = getTitle(html);
    const desc = getTag(html, 'description');
    const canonical = getCanonical(html);
    const refreshTarget = getRefreshTarget(html);
    const expectedCanonical = noindex && refreshTarget ? refreshTarget : expectedUrl;
    const textLen = stripHtml(html).length;
    if (!title) failures.push(`${r}: missing <title>`);
    else if (title.length < 10 || title.length > 80) warnings.push(`${r}: title length ${title.length}`);
    if (!desc) failures.push(`${r}: missing meta description`);
    else if (desc.length < 40 || desc.length > 180) warnings.push(`${r}: meta description length ${desc.length}`);
    if (!canonical) failures.push(`${r}: missing canonical`);
    else if (canonical !== expectedCanonical) failures.push(`${r}: canonical mismatch (${canonical} !== ${expectedCanonical})`);

    const minText = r.startsWith('blog/') && r.endsWith('/index.html') && r !== 'blog/index.html' ? 1400 : 250;
    if (!noindex && textLen < minText) warnings.push(`${r}: thin visible text candidate (${textLen} chars)`);

    for (const href of internalLinks(html)) {
      if (!localTargetExists(href, file)) failures.push(`${r}: broken internal asset/link ${href}`);
    }
  }

  for (const url of expectedToolUrls) {
    if (!toolSitemapSet.has(url)) failures.push(`special-chars/sitemap.xml missing indexed tool URL: ${url}`);
  }
  for (const url of toolSitemapUrls) {
    if (!sitemapSet.has(url)) failures.push(`special-chars/sitemap.xml contains URL outside the canonical sitemap: ${url}`);
  }

  const homepage = read(path.join(rootDir, 'index.html'));
  if (!getProperty(homepage, 'og:title')) failures.push('index.html missing Open Graph title');
  if (!getProperty(homepage, 'og:description')) failures.push('index.html missing Open Graph description');
  if (getProperty(homepage, 'og:url') !== `${origin}/`) failures.push('index.html Open Graph URL does not match the canonical homepage');
  if (!getProperty(homepage, 'og:image')) failures.push('index.html missing Open Graph image');
  if (getTag(homepage, 'google-adsense-account') !== 'ca-pub-3501868770820650') {
    failures.push('index.html missing the expected AdSense ownership meta tag');
  }
  const adsText = read(path.join(rootDir, 'ads.txt')).trim();
  if (adsText !== 'google.com, pub-3501868770820650, DIRECT, f08c47fec0942fa0') {
    failures.push('ads.txt publisher declaration does not match the configured AdSense account');
  }

  return { failures, warnings, sitemapUrls };
}

async function liveAudit(sitemapUrls) {
  const failures = [];
  const headers = { 'User-Agent': 'Googlebot/2.1 (+http://www.google.com/bot.html)' };
  const robots = await fetch(`${origin}/robots.txt`, { headers });
  if (!robots.ok) failures.push(`robots.txt HTTP ${robots.status}`);
  const robotsText = await robots.text();
  if (!/Sitemap:\s*https:\/\/teemozipsa\.com\/sitemap\.xml/i.test(robotsText)) {
    failures.push('robots.txt missing canonical sitemap URL');
  }

  const liveSitemap = await fetch(`${origin}/sitemap.xml`, { headers });
  if (!liveSitemap.ok) failures.push(`live sitemap HTTP ${liveSitemap.status}`);
  const liveXml = await liveSitemap.text();
  for (const url of sitemapUrls) {
    if (!liveXml.includes(`<loc>${url}</loc>`)) failures.push(`live sitemap missing ${url}`);
  }

  for (const url of sitemapUrls) {
    const res = await fetch(url, { headers, redirect: 'manual' });
    if (res.status >= 300 && res.status < 400) failures.push(`${url}: redirect ${res.status} to ${res.headers.get('location') || ''}`);
    else if (!res.ok) failures.push(`${url}: HTTP ${res.status}`);
  }

  for (const removed of [`${origin}/blog/article-template.html`, `${origin}/blog/article_template.html`, `${origin}/blog/article.html`]) {
    const res = await fetch(removed, { headers, redirect: 'manual' });
    if (res.status !== 404) failures.push(`${removed}: expected 404 after removing public template, got ${res.status}`);
  }

  return failures;
}

const { failures, warnings, sitemapUrls } = localAudit();
if (liveMode) {
  failures.push(...await liveAudit(sitemapUrls));
}

if (warnings.length) {
  console.warn(`SEO index audit warnings (${warnings.length}):`);
  warnings.slice(0, 80).forEach(w => console.warn(`- ${w}`));
  if (warnings.length > 80) console.warn(`- ... ${warnings.length - 80} more`);
}

if (failures.length) {
  console.error(`SEO index audit failed (${failures.length} issue${failures.length === 1 ? '' : 's'}):`);
  failures.forEach(f => console.error(`- ${f}`));
  process.exit(1);
}

console.log(`SEO index audit passed: ${sitemapUrls.length} sitemap URLs and local public HTML files are crawl-safe${liveMode ? ' on live site too' : ''}.`);
